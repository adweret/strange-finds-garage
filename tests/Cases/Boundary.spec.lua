return function()
	local shared = game:GetService("ReplicatedStorage").Garage
	local CargoManifest, RequestGuard = require(shared.CargoManifest), require(shared.RequestGuard)
	describe("Cargo carrier ownership", function()
		it("keeps a hand-carried find in one slot when approaching a vehicle", function()
			local manifest = CargoManifest.new()
			local owner, buggy = {}, { kind = "buggy" }
			manifest:claim(owner, 0, nil, false)
			expect(manifest:capacity(owner, 1, buggy, true)).to.equal(1)
			expect(manifest:canTake(owner, 1, buggy, true)).to.equal(false)
			expect(manifest:canUnload(owner, false)).to.equal(true)
		end)
		it("requires the original vehicle near pickups and unloading even for one find", function()
			local manifest = CargoManifest.new()
			local owner, cart, another = {}, { kind = "cart" }, { kind = "cart" }
			manifest:claim(owner, 0, cart, true)
			expect(manifest:capacity(owner, 1, cart, false)).to.equal(3)
			expect(manifest:canTake(owner, 1, cart, false)).to.equal(false)
			expect(manifest:canTake(owner, 1, another, true)).to.equal(false)
			expect(manifest:canUnload(owner, false)).to.equal(false)
			expect(manifest:canTake(owner, 2, cart, true)).to.equal(true)
			expect(manifest:canTake(owner, 3, cart, true)).to.equal(false)
		end)
		it("releases the old carrier on delivery, death or capture", function()
			local manifest = CargoManifest.new()
			local owner, buggy = {}, { kind = "buggy" }
			manifest:claim(owner, 0, buggy, true)
			manifest:clear(owner)
			expect(manifest:capacity(owner, 0, nil, false)).to.equal(1)
			manifest:claim(owner, 0, buggy, true)
			expect(manifest:capacity(owner, 1, buggy, true)).to.equal(6)
		end)
	end)
	describe("Exact remote intent contracts", function()
		it("accepts supported scalar intentions", function()
			expect(RequestGuard.valid("Deposit", nil)).to.equal(true)
			expect(RequestGuard.valid("Sell", { id = "mine" })).to.equal(true)
			expect(RequestGuard.valid("Sprint", { enabled = false })).to.equal(true)
		end)
		it("rejects invented rewards and nested or oversized payloads", function()
			expect(RequestGuard.valid("Sell", { id = "mine", coins = 100000 })).to.equal(false)
			expect(RequestGuard.valid("Sell", { id = {} })).to.equal(false)
			expect(RequestGuard.valid("Sell", { id = string.rep("x", 65) })).to.equal(false)
		end)
		it("rejects unknown actions and missing or mistyped fields", function()
			expect(RequestGuard.valid("GrantCoins", {})).to.equal(false)
			expect(RequestGuard.valid("VehicleProject", {})).to.equal(false)
			expect(RequestGuard.valid("Sprint", { enabled = 1 })).to.equal(false)
			expect(RequestGuard.valid({}, {})).to.equal(false)
		end)
	end)
end
